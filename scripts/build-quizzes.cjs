// quizzes/*.json is the only authored source; this bundle also works on file://.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const catalog = {};
for (const file of fs.readdirSync(path.join(root, 'quizzes')).filter(f => f.endsWith('.json')).sort((a,b) => a.localeCompare(b,undefined,{numeric:true}))) {
  const raw = JSON.parse(fs.readFileSync(path.join(root,'quizzes',file),'utf8'));
  const quizzes = Array.isArray(raw) ? raw : [raw];
  catalog[file] = quizzes.map((quiz,index) => {
    if (!quiz || !Array.isArray(quiz.questions) || !quiz.questions.length) throw new Error(`Invalid quiz: ${file}`);
    return {...quiz,id:quiz.id || `q-${file.replace('.json','')}-${index}`,sourceFile:file};
  });
}
fs.writeFileSync(path.join(root,'quizzes','catalog.js'),'// Generated by scripts/build-quizzes.cjs. Edit JSON files, not this bundle.\nwindow.QUIZ_CATALOG = '+JSON.stringify(catalog)+';\n');
console.log(`Prepared ${Object.keys(catalog).length} quiz files.`);
