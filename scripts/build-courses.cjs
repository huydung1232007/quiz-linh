const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname,'..');
// Preserve stable lesson IDs so saved videos, notes and completion still match.
const specification = [
  ['basics','Các khái niệm cơ bản','01 · Nền tảng','w02.1',29,'de-7.json'],
  ['conditions','Cấu trúc rẽ nhánh và điều kiện','01 · Nền tảng','w02.2',20,'de-1.json'],
  ['loops','Cấu trúc lặp','01 · Nền tảng','w02.3',19,'de-2.json'],
  ['lists','Các kiểu dữ liệu phức hợp: List','02 · Dữ liệu & tập tin','w03-',25,'de-5.json'],
  ['collections','Tuple, Set và Dictionary','02 · Dữ liệu & tập tin','w04.1',27,'de-4.json'],
  ['files','Xử lý tập tin','02 · Dữ liệu & tập tin','w04.2',21,null],
  ['functions','Hàm và module','03 · Tổ chức chương trình','w05-',36,'de-3.json'],
  ['strings','Xử lý chuỗi','03 · Tổ chức chương trình','w06-',16,'de-8.json'],
  ['numpy','Phân tích dữ liệu với NumPy','04 · Phân tích & biểu diễn dữ liệu','w10-',18,'de-14.json'],
  ['matplotlib','Biểu diễn dữ liệu với Matplotlib','04 · Phân tích & biểu diễn dữ liệu','w12-',32,'de-6.json']
];
const pdfFiles = fs.readdirSync(path.join(root,'tài liệu lý thuyết'));
const lessons = specification.map(([id,title,section,prefix,pages,quiz]) => {
  const matches = pdfFiles.filter(file => file.endsWith('.pdf') && file.includes('] '+prefix));
  if (matches.length !== 1) throw new Error('Missing or ambiguous PDF: '+id);
  const body = fs.readFileSync(path.join(root,'assets','theory',id+'.md'),'utf8').trim();
  return {id,title,section,quiz,duration:`${Math.ceil(body.split(/\s+/).length / 130 / 5) * 5} phút đọc`,
    summary:body.split('\n')[1],body,
    source:{file:'tài liệu lý thuyết/'+matches[0],name:matches[0],pages,author:'GV. Trần Quang Khải',course:'Nhập môn lập trình Python · IPPA233277'}};
});
fs.writeFileSync(path.join(root,'assets','course-data.js'),'// Generated by scripts/build-courses.cjs from assets/theory/*.md and the supplied PDF mapping.\nwindow.COURSE_LESSONS = '+JSON.stringify(lessons,null,2)+';\n');
console.log(`Prepared ${lessons.length} lessons with original PDF sources.`);
