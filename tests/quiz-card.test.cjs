const fs = require('fs'), vm = require('vm'), assert = require('node:assert/strict');
const ctx = {window:{addEventListener(){}},document:{readyState:'loading'},console};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('assets/exam-engine.js','utf8'),ctx);
const quiz = JSON.parse(fs.readFileSync('quizzes/de-1.json','utf8'));
ctx.quiz = quiz;
let card = vm.runInContext('app.renderQuizCard(quiz)',ctx);
assert(card.includes('#PY-COND-50'));
assert(card.includes('60p • 6 câu'));
assert(card.includes('Chưa làm'));
for (const action of ['startQuiz','openShareModal','openEditQuiz']) assert(card.includes('app.'+action));
vm.runInContext('app.history = [{quizId:quiz.id,score:8.3,dateLabel:"23/10/2026"}]',ctx);
card = vm.runInContext('app.renderQuizCard(quiz)',ctx);
assert(card.includes('Đã làm 1 lần'));
assert(card.includes('8.3/10 điểm'));
ctx.quiz = {...quiz,title:'<img src=x>',desc:'<script>bad</script>'};
card = vm.runInContext('app.renderQuizCard(quiz)',ctx);
assert(!card.includes('<img src=x>'));
assert(card.includes('&lt;script&gt;'));
console.log('PASS: shared quiz card metadata, controls, history and escaped text.');
